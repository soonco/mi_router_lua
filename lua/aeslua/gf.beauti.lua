--[[
================================================================================
AES 加密库 - 伽罗瓦域运算模块 (Galois Field Module)
================================================================================

功能说明：
  本模块实现了 GF(2^8) 伽罗瓦域（有限域）上的数学运算。
  AES 加密算法的核心运算都是在 GF(2^8) 上进行的。

伽罗瓦域 GF(2^8) 基础知识：
  - 元素数量：256 个（0 到 255）
  - 加法：按位异或 (XOR)
  - 乘法：多项式乘法后对不可约多项式取模
  - 不可约多项式：x^8 + x^4 + x^3 + x + 1（十进制 283）

本模块使用对数/指数表来加速乘法和除法运算：
  - 如果 g 是 GF(2^8) 的生成元
  - 则 a * b = g^(log_g(a) + log_g(b))
  - 这将乘法转换为查表和加法操作

主要接口：
  - gf.add(a, b)    : 加法（异或）
  - gf.sub(a, b)    : 减法（与加法相同）
  - gf.mul(a, b)    : 乘法
  - gf.div(a, b)    : 除法
  - gf.invert(a)    : 求逆元

================================================================================
--]]

-- 声明模块
module("aeslua.gf", package.seeall)

-- 加载位运算库
local bit = require("bit")

-- 创建内部配置表和导出表
local config = {}
local gf = {}

-- 将 gf 对象挂载到 aeslua 命名空间
aeslua.gf = gf

-- GF(2^8) 域参数
config.n = 256              -- 域中元素数量
config.ord = 255            -- 域的阶（非零元素数量）
config.irrPolynom = 283     -- 不可约多项式：x^8 + x^4 + x^3 + x + 1

-- 对数表和指数表（用于加速乘法/除法）
config.exp = {}             -- 指数表：exp[i] = g^i
config.log = {}             -- 对数表：log[a] = i，其中 g^i = a

--[[
--------------------------------------------------------------------------------
函数: gf.add(a, b)
--------------------------------------------------------------------------------
功能: GF(2^8) 加法

参数:
  a - 第一个操作数（0-255）
  b - 第二个操作数（0-255）

返回值:
  number - a + b 的结果

说明:
  在 GF(2^8) 中，加法就是按位异或 (XOR)。
  这是因为 GF(2) 中 1 + 1 = 0（模 2 加法）。
--------------------------------------------------------------------------------
--]]
function gf.add(a, b)
    return bit.bxor(a, b)
end

--[[
--------------------------------------------------------------------------------
函数: gf.sub(a, b)
--------------------------------------------------------------------------------
功能: GF(2^8) 减法

参数:
  a - 被减数（0-255）
  b - 减数（0-255）

返回值:
  number - a - b 的结果

说明:
  在 GF(2^8) 中，减法与加法相同（都是异或）。
  因为每个元素都是自己的加法逆元：a + a = 0。
--------------------------------------------------------------------------------
--]]
function gf.sub(a, b)
    return bit.bxor(a, b)
end

--[[
--------------------------------------------------------------------------------
函数: gf.invert(a)
--------------------------------------------------------------------------------
功能: 计算 GF(2^8) 中元素的乘法逆元

参数:
  a - 要求逆的元素（1-255，0 没有逆元）

返回值:
  number - a 的乘法逆元，即 a^(-1)，满足 a * a^(-1) = 1

说明:
  使用对数表计算：a^(-1) = g^(ord - log(a))
  其中 ord = 255 是域的阶。
--------------------------------------------------------------------------------
--]]
function gf.invert(a)
    if a == 1 then
        return 1
    end
    local logA = config.log[a]
    local expIndex = config.ord - logA
    return config.exp[expIndex]
end

--[[
--------------------------------------------------------------------------------
函数: gf.mul(a, b)
--------------------------------------------------------------------------------
功能: GF(2^8) 乘法

参数:
  a - 第一个乘数（0-255）
  b - 第二个乘数（0-255）

返回值:
  number - a * b 的结果

说明:
  使用对数表加速计算：a * b = g^(log(a) + log(b))
  特殊情况：任何数乘以 0 等于 0。
  如果指数超过 ord，需要取模（减去 ord）。
--------------------------------------------------------------------------------
--]]
function gf.mul(a, b)
    if a == 0 or b == 0 then
        return 0
    end
    
    local logA = config.log[a]
    local logB = config.log[b]
    local expIndex = logA + logB
    
    -- 如果指数超过阶，需要取模
    if expIndex >= config.ord then
        expIndex = expIndex - config.ord
    end
    
    return config.exp[expIndex]
end

--[[
--------------------------------------------------------------------------------
函数: gf.div(a, b)
--------------------------------------------------------------------------------
功能: GF(2^8) 除法

参数:
  a - 被除数（0-255）
  b - 除数（1-255，不能为 0）

返回值:
  number - a / b 的结果

说明:
  使用对数表计算：a / b = g^(log(a) - log(b))
  特殊情况：0 除以任何非零数等于 0。
  如果指数为负，需要加上 ord。
--------------------------------------------------------------------------------
--]]
function gf.div(a, b)
    if a == 0 then
        return 0
    end
    
    local logA = config.log[a]
    local logB = config.log[b]
    local expIndex = logA - logB
    
    -- 如果指数为负，需要加上阶
    if expIndex < 0 then
        expIndex = expIndex + config.ord
    end
    
    return config.exp[expIndex]
end

--[[
--------------------------------------------------------------------------------
函数: gf.printLog()
--------------------------------------------------------------------------------
功能: 打印对数表（调试用）
--------------------------------------------------------------------------------
--]]
function gf.printLog()
    for i = 1, config.n do
        print("log(", i - 1, ")=", config.log[i - 1])
    end
end

--[[
--------------------------------------------------------------------------------
函数: gf.printExp()
--------------------------------------------------------------------------------
功能: 打印指数表（调试用）
--------------------------------------------------------------------------------
--]]
function gf.printExp()
    for i = 1, config.n do
        print("exp(", i - 1, ")=", config.exp[i - 1])
    end
end

--[[
--------------------------------------------------------------------------------
函数: config.initMulTable()
--------------------------------------------------------------------------------
功能: 初始化对数表和指数表

说明:
  使用生成元 g = 3（即 x + 1）来构建表。
  
  算法：
  1. 从 g^0 = 1 开始
  2. 每次计算 g^(i+1) = g^i * g = g^i * 3
  3. 在 GF(2^8) 中，乘以 3 等于：左移一位后异或原值
  4. 如果结果超过 255，需要对不可约多项式取模（异或 283）
  5. 同时记录对数值
--------------------------------------------------------------------------------
--]]
function config.initMulTable()
    local value = 1  -- 从 g^0 = 1 开始
    
    for i = 0, config.ord - 1 do
        -- 记录 exp[i] = g^i
        config.exp[i] = value
        -- 记录 log[value] = i
        config.log[value] = i
        
        -- 计算下一个值：value = value * g = value * 3
        -- 在 GF(2^8) 中，乘以 3 等于：(value << 1) XOR value
        value = bit.bxor(bit.lshift(value, 1), value)
        
        -- 如果超过 255，需要对不可约多项式取模
        if value > config.ord then
            value = gf.sub(value, config.irrPolynom)
        end
    end
end

-- 模块加载时初始化乘法表
config.initMulTable()

-- 返回 gf 模块
return gf
