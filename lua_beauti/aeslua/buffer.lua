--[[
================================================================================
AES 加密库 - 缓冲区模块 (Buffer Module)
================================================================================

功能说明：
  本模块实现了一个高效的字符串缓冲区，用于优化大量字符串连接操作。
  
  在 Lua 中，直接使用 ".." 运算符连接大量字符串会导致性能问题，
  因为每次连接都会创建新的字符串对象。本模块采用类似于"绳索"(rope)
  的数据结构来优化这一操作。

工作原理：
  缓冲区使用一个数组来存储待连接的字符串片段。
  当添加新字符串时，模块会检查相邻元素的长度，
  如果前一个元素长度大于后一个元素，则进行合并操作。
  这种策略可以减少中间字符串的创建次数，提高内存效率。

主要接口：
  - buffer.new()        : 创建新的缓冲区对象
  - buffer.addString()  : 向缓冲区添加字符串
  - buffer.toString()   : 将缓冲区内容转换为最终字符串

使用示例：
  local buf = buffer.new()
  buffer.addString(buf, "Hello")
  buffer.addString(buf, " ")
  buffer.addString(buf, "World")
  local result = buffer.toString(buf)  -- "Hello World"

================================================================================
--]]

-- 声明模块
module("aeslua.buffer", package.seeall)

-- 创建缓冲区对象表
local buffer = {}

-- 将缓冲区对象挂载到 aeslua 命名空间
aeslua.buffer = buffer

--[[
--------------------------------------------------------------------------------
函数: buffer.new()
--------------------------------------------------------------------------------
功能: 创建一个新的空缓冲区对象

返回值:
  table - 新创建的空缓冲区（空数组）

说明:
  缓冲区本质上是一个 Lua 数组，用于存储待连接的字符串片段。
  初始状态为空数组 {}。
--------------------------------------------------------------------------------
--]]
function buffer.new()
    local newBuffer = {}
    return newBuffer
end

--[[
--------------------------------------------------------------------------------
函数: buffer.addString(buf, str)
--------------------------------------------------------------------------------
功能: 向缓冲区添加一个字符串

参数:
  buf - 缓冲区对象（由 buffer.new() 创建）
  str - 要添加的字符串

说明:
  添加字符串后，模块会从数组末尾开始检查：
  如果当前元素的长度大于下一个元素的长度，则将它们合并。
  这种合并策略基于以下观察：
  - 较短的字符串合并成本较低
  - 通过延迟合并较长的字符串，可以减少总体内存分配次数
  
  这是一种类似于"二项堆"的合并策略，可以将 n 次字符串连接的
  时间复杂度从 O(n²) 降低到 O(n log n)。
--------------------------------------------------------------------------------
--]]
function buffer.addString(buf, str)
    -- 将新字符串添加到缓冲区末尾
    buf[#buf + 1] = str
    
    -- 从倒数第二个元素开始，向前遍历
    -- 检查是否需要合并相邻的字符串
    for i = #buf - 1, 1, -1 do
        local currentLen = #buf[i]      -- 当前元素长度
        local nextLen = #buf[i + 1]     -- 下一个元素长度
        
        -- 如果当前元素比下一个元素长，停止合并
        -- 这保证了数组中的字符串长度大致呈递增趋势
        if currentLen > nextLen then
            break
        end
        
        -- 合并当前元素和最后一个元素
        local current = buf[i]
        local last = table.remove(buf)  -- 移除并获取最后一个元素
        buf[i] = current .. last        -- 合并字符串
    end
end

--[[
--------------------------------------------------------------------------------
函数: buffer.toString(buf)
--------------------------------------------------------------------------------
功能: 将缓冲区中的所有字符串合并为一个最终字符串

参数:
  buf - 缓冲区对象

返回值:
  string - 合并后的完整字符串

说明:
  此函数会将缓冲区中剩余的所有字符串片段从后向前依次合并，
  最终返回第一个元素（即完整的合并结果）。
  
  调用此函数后，缓冲区将只包含一个元素（最终结果）。
--------------------------------------------------------------------------------
--]]
function buffer.toString(buf)
    -- 从倒数第二个元素开始，向前合并所有字符串
    for i = #buf - 1, 1, -1 do
        local current = buf[i]
        local last = table.remove(buf)  -- 移除并获取最后一个元素
        buf[i] = current .. last        -- 合并到当前位置
    end
    
    -- 返回第一个元素（即合并后的完整字符串）
    return buf[1]
end

-- 返回缓冲区模块
return buffer
